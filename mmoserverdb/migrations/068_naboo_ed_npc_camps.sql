--   naboo_gungan_military_base_neutral_large_theater up to lvl 15 2500 m+    Gungan war chief (9, pistol_dl44), Gungan Captain (11, pistol_dl44), Gungan General (12, pistol_dl44), Gungan bomber (14, pistol_dl44), Gungan boss (15, pistol_dl44); pp. 450
