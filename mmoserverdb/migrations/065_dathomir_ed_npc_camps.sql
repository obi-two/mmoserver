-- Dathomir: An Empire Divided's NPC camps (docs/SPAWNS.md, roadmap step 3).
-- Written by tools/reference/npc_camps_sql.py --guide ed; edit that, not
-- this.
--
-- The planet's hostile, non-faction NPCs in An Empire Divided's tables
-- (pp. 426-428; mmoserverdb/reference/prima_ed/npcs.csv): those above level 11
-- and those the 2004 guide's table lacks. Each a template with the book's
-- stats, the client's model and name, and a weapon; each group in camps of
-- up to six kinds by level, 4 of each, placed at random on the planet in
-- the band of its strongest NPC's level, named after the group's camp in
-- the client's lair_n, each the client's camp building for the group where
-- the client has one, with an invisible lair (nothing to destroy).
--
-- Reconstructed, and data to tune: the book gives no weapons, so each NPC
-- carries one by group (Tusken rifles, Jawa ion rifles, stone knives for
-- the tribes, vibroblades for the Nightsisters and the Singing Mountain
-- clan) or by level (pistol below 15, carbine to 29, rifle above); models
-- for NPCs the client has no outfit of their own for (the group's);
-- splitting large groups by level; the camps. Camps call 4 at a time.
--
--   dathomir_nightsister_outcast_camp_neutral_small_theater up to lvl 75 4500 m+    Nightsister sentry (20, knife_vibroblade), Nightsister initiate (50, knife_vibroblade), Nightsister rancor (50, unarmed), Nightsister outcast (75, knife_vibroblade); pp. 426
--   dathomir_nightsister_elder_enclave_neutral_large_theater up to lvl 85 4500 m+    Nightsister rancor tamer (75, knife_vibroblade), Nightsister ranger (75, knife_vibroblade), Nightsister stalker (85, knife_vibroblade); pp. 426
--   dathomir_mtn_clan_outcast_camp_neutral_small_theater up to lvl 75 4500 m+    Singing Mountain clan sentry (20, knife_vibroblade), Singing Mountain clan rancor (50, unarmed), Singing Mountain clan initiate (50, knife_vibroblade), Singing Mountain clan huntress (75, knife_vibroblade); pp. 426, 428
--   dathomir_mtn_clan_outpost_neutral_large_theater up to lvl 95 4500 m+    Singing Mountain clan outcast (75, knife_vibroblade), Singing Mountain clan rancor tamer (75, knife_vibroblade), Singing Mountain clan scout (75, knife_vibroblade), Singing Mountain clan dragoon (95, knife_vibroblade); pp. 428
--

